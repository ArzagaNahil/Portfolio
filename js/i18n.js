let currentLang = DEFAULT_LANG;
let onLangChange = null;

function apply() {
    const dict = I18N[currentLang] || I18N.es;

    document.querySelectorAll('[data-i18n]').forEach((el) => {
        const key = el.dataset.i18n;
        if (!key || !(key in dict)) return;

        const offset = el.querySelector(':scope > .page-title__offset, :scope > .tile__title__offset');

        if (offset && el.dataset.i18nOffset) {
            const offsetKey = el.dataset.i18nOffset;
            el.childNodes.forEach((node) => {
                if (node.nodeType === 3) node.data = '';
            });
            offset.textContent = offsetKey in dict ? dict[offsetKey] : dict[key];
            el.insertBefore(document.createTextNode(dict[key]), offset);
            return;
        }

        if (el.matches('.menu__item')) {
            el.dataset.label = dict[key];
            el.textContent = dict[key];
            return;
        }

        el.textContent = dict[key];
    });

    document.querySelectorAll('[data-i18n-attr]').forEach((el) => {
        const attr = el.dataset.i18nAttr;
        const key = el.dataset.i18nKey;
        if (attr && key && key in dict) el.setAttribute(attr, dict[key]);
    });

    document.querySelectorAll('[data-i18n-toggle]').forEach((toggle) => {
        const target = currentLang === 'es' ? 'en' : 'es';
        toggle.textContent = target.toUpperCase();
        toggle.setAttribute('aria-label', currentLang === 'es' ? 'Cambiar a inglés' : 'Switch to Spanish');
    });
}

export function getLang() {
    return currentLang;
}

export function setLang(lang) {
    const next = SUPPORTED_LANGS.includes(lang) ? lang : DEFAULT_LANG;
    if (next === currentLang) return;

    currentLang = next;
    document.documentElement.lang = next;
    try {
        localStorage.setItem('lang', next);
    } catch (e) {}

    apply();
    if (typeof onLangChange === 'function') onLangChange(next);
}

export function initI18n(callback) {
    if (typeof callback === 'function') onLangChange = callback;

    let lang = DEFAULT_LANG;
    try {
        const saved = localStorage.getItem('lang');
        if (saved && SUPPORTED_LANGS.includes(saved)) lang = saved;
    } catch (e) {}

    currentLang = lang;
    document.documentElement.lang = lang;
    apply();

    document.querySelectorAll('[data-i18n-toggle]').forEach((toggle) => {
        toggle.addEventListener('click', () => {
            setLang(currentLang === 'es' ? 'en' : 'es');
        });
    });
}